n1 = int(input("Enter the to start the operations: "))
n2 = int(input("Enter the second number for the operations: "))
x = input(" the operator to accomplish the operations: ")

if x == "+":
    print("The answer is:",n1 + n2, "have a great day :)")
elif x == "-":
    print("The answer is:",n1 - n2, "have a great day :)")
elif x == "/":
    print("The answer is:",n1 / n2, "have a great day :)")
elif x == "*":
    print("The answer is:", n1 * n2, "have a great day :)")
else:
    print("Vivan las mujeres")